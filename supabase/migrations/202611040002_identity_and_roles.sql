create table public.roles (
  id smallint generated by default as identity primary key,
  code text not null unique,
  description text not null,
  constraint roles_code_check check (
    code in ('super_admin', 'admin', 'operator', 'driver', 'customer')
  )
);

insert into public.roles (code, description)
values
  ('super_admin', 'Full administrative control through guarded server operations.'),
  ('admin', 'Administrative and finance operations.'),
  ('operator', 'Booking review, quote issuance, and driver/vehicle assignment.'),
  ('driver', 'Assigned trip operations.'),
  ('customer', 'Customer booking and quote access.')
on conflict (code) do nothing;

create table public.profiles (
  id uuid primary key references auth.users (id) on delete restrict,
  full_name text not null,
  phone text,
  account_status text not null default 'active',
  created_at timestamptz not null default pg_catalog.now(),
  updated_at timestamptz not null default pg_catalog.now(),
  constraint profiles_account_status_check
    check (account_status in ('active', 'inactive'))
);

create trigger profiles_set_updated_at
before update on public.profiles
for each row execute function private.set_updated_at();

create table public.user_roles (
  id uuid primary key default pg_catalog.gen_random_uuid(),
  user_id uuid not null references public.profiles (id) on delete cascade,
  role_id smallint not null references public.roles (id) on delete restrict,
  assigned_by uuid references public.profiles (id) on delete set null,
  assigned_at timestamptz not null default pg_catalog.now(),
  revoked_at timestamptz,
  constraint user_roles_revoked_after_assignment
    check (revoked_at is null or revoked_at >= assigned_at)
);

create unique index user_roles_one_active_role_per_user
  on public.user_roles (user_id, role_id)
  where revoked_at is null;
create index user_roles_role_user_idx on public.user_roles (role_id, user_id);

create or replace function private.is_active_user()
returns boolean
language sql
stable
security definer
set search_path = ''
as $function$
  select exists (
    select 1
      from public.profiles as p
     where p.id = (select auth.uid())
       and p.account_status = 'active'
  );
$function$;

revoke all on function private.is_active_user()
  from public, anon, authenticated, service_role;
grant usage on schema private to authenticated;
grant execute on function private.is_active_user() to authenticated;

create table private.privileged_audit_events (
  id uuid primary key default pg_catalog.gen_random_uuid(),
  event_type text not null,
  actor_user_id uuid references public.profiles (id) on delete set null,
  target_user_id uuid references public.profiles (id) on delete set null,
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default pg_catalog.now()
);

alter table private.privileged_audit_events enable row level security;
revoke all on table private.privileged_audit_events
  from public, anon, authenticated, service_role;

create or replace function public.handle_new_auth_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $function$
declare
  v_customer_role_id smallint;
begin
  insert into public.profiles (id, full_name, phone)
  values (
    new.id,
    coalesce(
      nullif(pg_catalog.btrim(new.raw_user_meta_data ->> 'full_name'), ''),
      'New customer'
    ),
    nullif(pg_catalog.btrim(new.raw_user_meta_data ->> 'phone'), '')
  )
  on conflict (id) do nothing;

  select r.id
    into v_customer_role_id
    from public.roles as r
   where r.code = 'customer';

  if v_customer_role_id is null then
    raise exception 'Customer role is not configured';
  end if;

  insert into public.user_roles (user_id, role_id)
  select new.id, v_customer_role_id
   where not exists (
     select 1
       from public.user_roles as ur
      where ur.user_id = new.id
        and ur.role_id = v_customer_role_id
        and ur.revoked_at is null
   )
  on conflict do nothing;

  return new;
end;
$function$;

revoke all on function public.handle_new_auth_user()
  from public, anon, authenticated, service_role;

create trigger on_auth_user_created
after insert on auth.users
for each row execute function public.handle_new_auth_user();

create or replace function private.bootstrap_first_super_admin(p_user_id uuid)
returns void
language plpgsql
security definer
set search_path = ''
as $function$
declare
  v_super_admin_role_id smallint;
begin
  perform pg_catalog.pg_advisory_xact_lock(74123, 1);

  if exists (
    select 1
      from public.user_roles as ur
      join public.roles as r on r.id = ur.role_id
     where r.code = 'super_admin'
       and ur.revoked_at is null
  ) then
    raise exception 'Super Admin bootstrap has already been completed';
  end if;

  if not exists (
    select 1
      from public.profiles as p
     where p.id = p_user_id
       and p.account_status = 'active'
  ) then
    raise exception 'Target must be an existing active Auth profile';
  end if;

  select r.id
    into v_super_admin_role_id
    from public.roles as r
   where r.code = 'super_admin';

  if v_super_admin_role_id is null then
    raise exception 'Super Admin role is not configured';
  end if;

  insert into public.user_roles (user_id, role_id)
  values (p_user_id, v_super_admin_role_id);

  insert into private.privileged_audit_events (
    event_type,
    target_user_id,
    details
  )
  values (
    'initial_super_admin_bootstrap',
    p_user_id,
    jsonb_build_object('created_at', pg_catalog.now())
  );
end;
$function$;

revoke all on function private.bootstrap_first_super_admin(uuid)
  from public, anon, authenticated, service_role;
grant execute on function private.bootstrap_first_super_admin(uuid) to postgres;

